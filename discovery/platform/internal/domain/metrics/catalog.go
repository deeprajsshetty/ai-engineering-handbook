// Package metrics defines metric semantics: names, units, the resource types
// each metric applies to, and the provenance of samples. It has no I/O.
package metrics

import (
	"sort"
	"time"
)

// Source states where a sample came from. The UI and API always expose it so
// simulated values are never mistaken for measurements.
type Source string

const (
	SourceSimulated Source = "simulated" // generated by the deterministic local generator
	SourceMeasured  Source = "measured"  // read from a real provider metrics API
)

// Definition describes one metric. Units follow UCUM-style notation used by
// OpenTelemetry semantic conventions: "%", "By", "By/s", "ms", "{request}/s".
type Definition struct {
	Name          string   `json:"name"`
	Unit          string   `json:"unit"`
	Description   string   `json:"description"`
	Kind          string   `json:"kind"` // gauge only in the MVP
	ResourceTypes []string `json:"resourceTypes"`
	Min           float64  `json:"min"`
	Max           float64  `json:"max"` // 0 means unbounded
}

// Sample is one timestamped value for a resource and metric. Timestamps are
// UTC and aligned to the collection interval by the collector.
type Sample struct {
	TenantID   string    `json:"-"`
	ResourceID string    `json:"resourceId"`
	Metric     string    `json:"metric"`
	Timestamp  time.Time `json:"ts"`
	Value      float64   `json:"value"`
	Source     Source    `json:"source"`
	Collector  string    `json:"collector"`
}

