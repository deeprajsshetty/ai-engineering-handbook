var byName = func() map[string]Definition {
	m := make(map[string]Definition, len(catalog))
	for _, d := range catalog {
		m[d.Name] = d
	}
	return m
}()

var byType = func() map[string][]Definition {
	m := map[string][]Definition{}
	for _, d := range catalog {
		for _, t := range d.ResourceTypes {
			m[t] = append(m[t], d)
		}
	}
	return m
}()

// All returns every definition sorted by name.
func All() []Definition {
	out := append([]Definition(nil), catalog...)
	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out
}

// Lookup returns the definition for name.
func Lookup(name string) (Definition, bool) { d, ok := byName[name]; return d, ok }

// ForType returns the metrics that apply to a canonical resource type.
func ForType(resourceType string) []Definition { return byType[resourceType] }

// Supported reports whether any metric applies to the resource type.
func Supported(resourceType string) bool { return len(byType[resourceType]) > 0 }

// SupportedTypes returns all resource types that have at least one metric.
func SupportedTypes() []string {
	out := make([]string, 0, len(byType))
	for t := range byType {
		out = append(out, t)
	}
	sort.Strings(out)
	return out
}

// Clamp bounds v to the definition's range.
func (d Definition) Clamp(v float64) float64 {
	if v < d.Min {
		return d.Min
	}
	if d.Max > 0 && v > d.Max {
		return d.Max
	}
	return v
}
