#!/usr/bin/env bash
# Generates docs/inventory/dependencies-and-licenses.md from authoritative
# local metadata: Go module LICENSE files (module cache) and npm package.json
# "license" fields in node_modules. Run `make deps` first. No license is
# guessed: anything not detected is reported as needing review.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT/platform"
GOMOD="$(go env GOMODCACHE)"
GOLIST="$(go list -m -f '{{if not .Main}}{{.Path}} {{.Version}} {{if .Indirect}}indirect{{else}}direct{{end}}{{end}}' all)"
LINKED="$(go list -deps -f '{{if .Module}}{{.Module.Path}}{{end}}' ./cmd/obsplatform | sort -u)"
TESTLINKED="$(go list -deps -test -f '{{if .Module}}{{.Module.Path}}{{end}}' ./... | sort -u)"
python3 -I - "$GOMOD" "$ROOT/platform/web" <<PY
import json, os, sys
cache, web = sys.argv[1], sys.argv[2]
golist = """$GOLIST""".strip().splitlines()
linked = set("""$LINKED""".split())
testlinked = set("""$TESTLINKED""".split())
def detect(path):
    for n in ("LICENSE", "LICENSE.txt", "LICENSE.md", "COPYING", "LICENCE"):
        p = os.path.join(path, n)
        if os.path.exists(p):
            t = open(p, errors="ignore").read()
            if "Apache License" in t and "Version 2.0" in t: return "Apache-2.0"
            if "Permission is hereby granted, free of charge" in t: return "MIT"
            if "Redistribution and use in source and binary forms" in t:
                return "BSD-3-Clause" if ("Neither the name" in t or "names of its" in t) else "BSD-2-Clause"
            if "Mozilla Public License" in t: return "MPL-2.0"
            if "Permission to use, copy, modify, and/or distribute" in t: return "ISC"
            return "REVIEW (unrecognised LICENSE text)"
    return "n/a: graph-only, not downloaded or compiled"
print("# Dependency and license inventory (generated)\n")
print("Generated by \`make licenses\` (scripts/license-inventory.sh) from the Go module cache LICENSE files and npm package metadata. Detection is text-based and conservative; anything not recognised is marked REVIEW. This is an engineering inventory, not legal advice.\n")
print("## Go modules (platform/go.mod)\n")
print("| Module | Version | Direct/indirect | In server binary | In tests only | License (detected) |")
print("|---|---|---|---|---|---|")
for l in golist:
    p, v, d = l.split()
    esc = "".join("!" + c.lower() if c.isupper() else c for c in p)
    lic = detect(os.path.join(cache, f"{esc}@{v}"))
    inbin = "yes" if p in linked else "no"
    tests = "yes" if (p in testlinked and p not in linked) else "no"
    print(f"| {p} | {v} | {d} | {inbin} | {tests} | {lic} |")
print("\nModules listed with *In server binary = no* and *In tests only = no* are present in the module graph (go.sum) but not compiled into any package.\n")
lock = json.load(open(os.path.join(web, "package-lock.json")))
rows = []
for k, meta in lock.get("packages", {}).items():
    if not k: continue
    name = k.split("node_modules/")[-1]
    pj = os.path.join(web, k, "package.json")
    lic = "n/a: optional platform binary not installed on this OS" if meta.get("optional") else "REVIEW (not installed)"
    if os.path.exists(pj):
        d = json.load(open(pj))
        lic = d.get("license") or (d.get("licenses") and ",".join(x.get("type","?") for x in d["licenses"])) or "REVIEW (no license field)"
        if isinstance(lic, dict): lic = lic.get("type", "REVIEW")
    rows.append((name, meta.get("version",""), "dev" if meta.get("dev") else "prod", "yes" if k.count("node_modules/")==1 and (name in lock["packages"][""].get("dependencies",{}) or name in lock["packages"][""].get("devDependencies",{})) else "no", lic))
rows.sort()
from collections import Counter
print("## npm packages (platform/web/package-lock.json)\n")
c = Counter(r[4] for r in rows)
print("License summary: " + ", ".join(f"{k}: {v}" for k, v in sorted(c.items(), key=lambda x: -x[1])) + "\n")
print(f"Production packages (shipped in the browser bundle): {sum(1 for r in rows if r[2]=='prod')}; development/test-only: {sum(1 for r in rows if r[2]=='dev')}.\n")
print("| Package | Version | Scope | Direct | License (package.json) |")
print("|---|---|---|---|---|")
for r in rows: print("| " + " | ".join(r) + " |")
PY
